def normalised_indicators(Y,is_cost_mask):
    Yn=np.zeros_like(Y,float)
    if NORMALISATION == "rank":
        from scipy.stats import rankdata
        for j in range(Y.shape[1]):
            Yn[:,j]=(rankdata(Y[:,j],method="average")-1)/(Y.shape[0]-1)
    else:
        for j in range(Y.shape[1]):
            col=Y[:,j]; lo,hi=np.nanmin(col),np.nanmax(col)
            Yn[:,j]=0.5 if (not np.isfinite(lo+hi) or hi==lo) else (col-lo)/(hi-lo)
    Yn[:,is_cost_mask]=1-Yn[:,is_cost_mask]
    return Yn

def topsis_cc(Y_norm,w):
    Z=Y_norm*w; zp,zm=Z.max(0),Z.min(0)
    dp=np.linalg.norm(Z-zp,axis=1); dm=np.linalg.norm(Z-zm,axis=1)
    return dm/(dp+dm+1e-12)

def sample_dirichlet_floor(alpha,rng,min_w=MIN_WITHIN_W,max_tries=5000):
    alpha=np.asarray(alpha,float)
    for _ in range(max_tries):
        w=rng.dirichlet(alpha)
        if (w>=min_w).all(): return w
    return w

