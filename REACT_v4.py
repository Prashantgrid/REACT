def R_of_ri(ri_import):
    """Normative screening score; positive ri denotes net-import dependence."""
    if ri_import <= -0.5: return 0.8
    if -0.5 < ri_import < -0.1: return 1.0 + 0.5*(ri_import + 0.1)
    if abs(ri_import) <= 0.1: return 1.0
    if 0.1 < ri_import <= 0.3: return 1.0 - 4.0*(ri_import - 0.1)
    return 0.2

