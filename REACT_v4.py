def _nearest_corr(R, eps=1e-8):
    R = (R + R.T)/2
    vals, vecs = np.linalg.eigh(R)
    vals = np.maximum(vals, eps)
    R2 = vecs @ np.diag(vals) @ vecs.T
    d = np.sqrt(np.diag(R2))
    return R2 / np.outer(d,d)

def _pseudo_observations(hazard, hcols):
    rows=[]
    for s in sorted(hazard["State"].unique()):
        d=hazard[hazard["State"]==s].sort_values("Year")
        U=np.full((len(d),len(hcols)),np.nan)
        for j,c in enumerate(hcols):
            x=d[c].to_numpy(float); mask=~np.isnan(x)
            if mask.sum()>=2:
                U[mask,j]=rankdata(x[mask],method="average")/(mask.sum()+1)
        rows.append(U)
    U=np.vstack(rows)
    return np.clip(U[~np.isnan(U).any(axis=1)],1e-7,1-1e-7)

def estimate_copula(hazard, hcols):
    from statsmodels.distributions.copula.api import GaussianCopula, StudentTCopula
    U = _pseudo_observations(hazard,hcols)
    k_dim=len(hcols); k_corr=k_dim*(k_dim-1)//2
    base=GaussianCopula(k_dim=k_dim)
    R=_nearest_corr(base.fit_corr_param(U))
    g=GaussianCopula(corr=R,k_dim=k_dim,allow_singular=True)
    ll_g=float(np.sum(g.logpdf(U))); aic_g=2*k_corr-2*ll_g
    best=(aic_g,"gaussian",None,ll_g)
    for df in np.arange(3.0,30.5,0.5):
        tc=StudentTCopula(corr=R,df=float(df),k_dim=k_dim)
        ll=float(np.sum(tc.logpdf(U)))
        aic=2*(k_corr+1)-2*ll
        if np.isfinite(aic) and aic<best[0]: best=(aic,"student_t",float(df),ll)
    states=sorted(hazard["State"].unique())
    marginals={}
    for s in states:
        d=hazard[hazard["State"]==s].sort_values("Year")
        marginals[s]={c:np.sort(d[c].dropna().to_numpy(float)) for c in hcols}
    fit={"model":best[1],"df":best[2],"R":R,"marginals":marginals,
         "states":states,"n_complete":len(U),"aic_gaussian":aic_g,
         "aic_selected":best[0],"loglik_selected":best[3]}
    return fit

def _copula_quantile(fit,rng):
    from scipy.stats import t as student_t
    R=fit["R"]; p=R.shape[0]
    g=rng.multivariate_normal(np.zeros(p),R)
    if fit["model"]=="student_t":
        df=fit["df"]
        z=g/np.sqrt(rng.chisquare(df)/df)
        return student_t.cdf(z,df)
    return norm.cdf(g)

def sample_hazard_year(fit,hcols,spatial_coherent,rng):
    out={}; shared=_copula_quantile(fit,rng) if spatial_coherent else None
    for s in fit["states"]:
        u=shared if spatial_coherent else _copula_quantile(fit,rng)
        row={}
        for j,c in enumerate(hcols):
            xs=fit["marginals"][s][c]
            if len(xs)<2: row[c]=float("nan"); continue
            q=float(np.clip(u[j],0,1))*(len(xs)-1)
            lo=int(np.floor(q)); hi=min(len(xs)-1,lo+1); t=q-lo
            row[c]=(1-t)*xs[lo]+t*xs[hi]
        out[s]=row
    return out

